"""Build a Colab bundle for LoRA fine-tuning (plan v3, R3 / R6).

  .venv/bin/python forecasting/risk_experiment/colab/make_bundle.py dev
  HOLDOUT_UNLOCK=1 .venv/bin/python forecasting/risk_experiment/colab/make_bundle.py holdout   (after pre-registration)

The bundle is a folder plus a zip under forecasting/runs/risk/colab/:
  data/{ret,rv,eligible}.parquet  panels PHYSICALLY truncated at the mode's cutoff
  code/{alpha_lib,chronos_sources,ft_core}.py
  parity/*.parquet                local zero-shot reference forecasts for a few anchors (Colab must match)
  config.json                     mode, cutoff, folds, protocol constants, file hashes
  ft_lora.ipynb                   the notebook (generated by build_notebook.py)
No raw AlgoPack files, no API key.
"""
import hashlib
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
RISK = HERE.parent
ROOT = RISK.parents[1]
sys.path.insert(0, str(HERE)); sys.path.insert(0, str(RISK)); sys.path.insert(0, str(ROOT / "forecasting" / "alpha_experiment"))
import ft_core as fc  # noqa: E402

RUNS = ROOT / "forecasting" / "runs"
CUTOFF = {"dev": "2024-12-31", "holdout": "2026-09-17"}
PANEL = {"dev": RUNS / "alpha_data", "holdout": RUNS / "alpha_data_holdout"}
PARITY_ANCHORS = ["2021-06-01", "2023-03-01", "2024-10-01"]
PARITY_SOURCES = {"F1": RUNS / "alpha_variants" / "rv_xl" / "preds.parquet",        # Z3: log-RV, xl, ctx 250, H=5
                  "F2": RUNS / "risk" / "sources" / "dev" / "N1" / "preds.parquet"}  # N1: [ret, log-RV], xl


def prereg_commit_ok() -> bool:
    """Holdout bundles need a committed pre-registration block in the risk README."""
    readme = RISK / "README.md"
    if "<!-- PREREG_END -->" not in readme.read_text():
        return False
    log = subprocess.run(["git", "log", "--format=%H", "-S", "<!-- PREREG_END -->", "--", str(readme)],
                         cwd=ROOT, capture_output=True, text=True).stdout.strip()
    return bool(log)


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()[:16]


def build(mode: str) -> Path:
    if mode == "holdout" and (os.environ.get("HOLDOUT_UNLOCK") != "1" or not prereg_commit_ok()):
        raise SystemExit("holdout bundle refused: needs HOLDOUT_UNLOCK=1 and a committed pre-registration block")
    out = RUNS / "risk" / "colab" / f"bundle_{mode}"
    if out.exists():
        shutil.rmtree(out)
    (out / "data").mkdir(parents=True); (out / "code").mkdir(); (out / "parity").mkdir()
    cut = pd.Timestamp(CUTOFF[mode])
    for n in ("ret", "rv", "eligible"):
        df = pd.read_parquet(PANEL[mode] / f"{n}.parquet")
        df = df.loc[df.index <= cut]
        assert df.index.max() <= cut
        df.to_parquet(out / "data" / f"{n}.parquet")
    for src in (ROOT / "forecasting/alpha_experiment/alpha_lib.py", RISK / "chronos_sources.py", HERE / "ft_core.py"):
        shutil.copy(src, out / "code" / src.name)
    parity = {}
    if mode == "dev":                                                  # zero-shot references from the local runs
        for tgt, f in PARITY_SOURCES.items():
            if not f.exists():
                raise SystemExit(f"parity source missing: {f} (run risk_run.py sources_dev first)")
            p = pd.read_parquet(f)
            p = p[p["anchor"].isin(pd.DatetimeIndex(PARITY_ANCHORS))]
            if "variate" not in p.columns:
                p = p.assign(variate="logrv")
            p = p[p["h"] <= fc.H]
            p.to_parquet(out / "parity" / f"{tgt}_zero_shot_ref.parquet")
            parity[tgt] = {"source": str(f.relative_to(ROOT)), "rows": len(p)}
    subprocess.run([sys.executable, str(HERE / "build_notebook.py"), str(out / "ft_lora.ipynb"), mode], check=True)
    if mode == "holdout":                                               # only the fine-tuned sources a frozen arm needs
        import holdout_run
        run_targets = list(holdout_run.F_SOURCES)
    else:
        run_targets = list(fc.TARGETS)
    cfg = {"mode": mode, "cutoff": CUTOFF[mode], "folds": {str(k): v for k, v in fc.FOLDS[mode].items()},
           "targets": fc.TARGETS, "run_targets": run_targets, "ctx": fc.CTX, "H": fc.H, "lr_grid": list(fc.LR_GRID), "num_steps": fc.NUM_STEPS,
           "val_days": fc.VAL_DAYS, "val_stride": fc.VAL_STRIDE, "parity_anchors": PARITY_ANCHORS, "parity": parity,
           "chronos_forecasting": "2.3.2", "model": "amazon/chronos-2",
           "sha256_16": {str(p.relative_to(out)): sha(p) for p in sorted(out.rglob("*")) if p.is_file()}}
    (out / "config.json").write_text(json.dumps(cfg, indent=1))
    zp = shutil.make_archive(str(out), "zip", root_dir=out)
    print(f"bundle: {out}\nzip:    {zp}  ({Path(zp).stat().st_size / 1e6:.1f} MB)")
    return out


if __name__ == "__main__":
    build(sys.argv[1] if len(sys.argv) > 1 else "dev")
